package com.posplatform.modules.organization;

import com.posplatform.shared.domain.Auditable;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import org.hibernate.annotations.UuidGenerator;
import org.hibernate.annotations.UuidGenerator.Style;

import java.util.UUID;

/**
 * The tenant root. Business client of the platform.
 * Note: organization has no tenant_id column — it IS the tenant; its RLS
 * policy compares its own id against the transaction-bound tenant setting.
 */
@Entity
@Table(name = "organization")
public class Organization extends Auditable {

    public enum Status { ACTIVE, SUSPENDED }

    @Id
    private UUID id;                 // generated BY CODE (UuidV7) so tenant scope can be bound before insert

    @Column(nullable = false, length = 120)
    private String name;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, columnDefinition = "text")
    private Status status = Status.ACTIVE;

    /**
     * Business vertical (giro). Drives the declarative inventory/product
     * profile (ADR-010): units of measure, tracking dimensions, policies.
     * Free logic per tenant is FORBIDDEN — a vertical is code + catalog.
     */
    @Column(name = "vertical_code", nullable = false, length = 32)
    private String verticalCode = VerticalProfile.Code.CUSTOM;

    protected Organization() {
    }

    public Organization(UUID id, String name) {
        this.id = id;
        this.name = name;
        this.status = Status.ACTIVE;
        this.verticalCode = VerticalProfile.Code.CUSTOM;
    }

    public UUID getId() { return id; }
    public String getName() { return name; }
    public Status getStatus() { return status; }
    public String getVerticalCode() { return verticalCode; }

    public void changeVertical(String code) {
        VerticalProfile.requireKnown(code);
        this.verticalCode = code;
    }
}
