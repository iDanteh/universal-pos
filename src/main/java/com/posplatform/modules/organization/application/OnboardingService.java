package com.posplatform.modules.organization.application;

import com.posplatform.modules.identity.AppUser;
import com.posplatform.modules.identity.Membership;
import com.posplatform.modules.identity.MembershipRole;
import com.posplatform.modules.identity.Role;
import com.posplatform.modules.identity.infrastructure.MembershipRepository;
import com.posplatform.modules.identity.infrastructure.MembershipRoleRepository;
import com.posplatform.modules.organization.Branch;
import com.posplatform.modules.organization.LegalEntity;
import com.posplatform.modules.organization.Organization;
import com.posplatform.modules.organization.application.ports.RoleProvisioning;
import com.posplatform.modules.organization.application.ports.SubscriptionActivation;
import com.posplatform.modules.organization.application.ports.UserProvisioning;
import com.posplatform.modules.organization.infrastructure.BranchRepository;
import com.posplatform.modules.organization.infrastructure.LegalEntityRepository;
import com.posplatform.modules.organization.infrastructure.OrganizationRepository;
import com.posplatform.modules.subscription.Subscription;
import com.posplatform.shared.domain.UuidV7;
import com.posplatform.shared.outbox.OutboxWriter;
import jakarta.validation.Valid;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.validation.annotation.Validated;

import java.util.Map;
import java.util.UUID;

/**
 * ONBOARDING use case: creates the whole organizational backbone for a new
 * tenant in ONE ACID transaction:
 *
 *   organization + legal entity + branch + OWNER role + membership role link
 *   + membership + trial subscription + outbox domain event
 *
 * TRANSACTIONS AND RLS:
 *  - The new tenant id is generated by code to bind the PostgreSQL transaction
 *    context BEFORE the first insert (RLS policy on organization checks
 *    organization.id = current tenant; all child tables key tenant_id).
 *  - All inserts happen inside a single transaction so an error anywhere
 *    (e.g. trial plan missing) rolls the entire graph back.
 *
 * VALIDATION: command shape is validated with Bean Validation through
 * {@link Validated}; business invariants are DB constraints + code checks.
 */
@Service
@Validated
public class OnboardingService {

    private final OrganizationRepository organizationRepository;
    private final LegalEntityRepository legalEntityRepository;
    private final BranchRepository branchRepository;
    private final MembershipRepository membershipRepository;
    private final MembershipRoleRepository membershipRoleRepository;
    private final UserProvisioning userProvisioning;
    private final RoleProvisioning roleProvisioning;
    private final SubscriptionActivation subscriptionActivation;
    private final OutboxWriter outboxWriter;
    private final com.posplatform.shared.tenancy.TenantTransactionRunner tenantRunner;

    public OnboardingService(
            OrganizationRepository organizationRepository,
            LegalEntityRepository legalEntityRepository,
            BranchRepository branchRepository,
            MembershipRepository membershipRepository,
            MembershipRoleRepository membershipRoleRepository,
            UserProvisioning userProvisioning,
            RoleProvisioning roleProvisioning,
            SubscriptionActivation subscriptionActivation,
            OutboxWriter outboxWriter,
            com.posplatform.shared.tenancy.TenantTransactionRunner tenantRunner) {
        this.organizationRepository = organizationRepository;
        this.legalEntityRepository = legalEntityRepository;
        this.branchRepository = branchRepository;
        this.membershipRepository = membershipRepository;
        this.membershipRoleRepository = membershipRoleRepository;
        this.userProvisioning = userProvisioning;
        this.roleProvisioning = roleProvisioning;
        this.subscriptionActivation = subscriptionActivation;
        this.outboxWriter = outboxWriter;
        this.tenantRunner = tenantRunner;
    }

    @Transactional
    public OnboardOrganizationResult onboard(@Valid OnboardOrganizationCommand command) {
        UUID tenantId = UuidV7.next();

        return tenantRunner.run(tenantId, () -> {
            Organization organization = organizationRepository.save(
                    new Organization(tenantId, command.organizationName()));

            LegalEntity legalEntity = legalEntityRepository.save(new LegalEntity(
                    organization, command.legalName(), command.tradeName(), command.taxId()));

            Branch branch = branchRepository.save(new Branch(
                    tenantId, legalEntity, command.branchName(), command.branchCity()));

            AppUser owner = userProvisioning.createUserOrExisting(
                    command.ownerEmail(), command.ownerDisplayName(),
                    organization.getId(), organization.getName());

            Role ownerRole = roleProvisioning.createOwnerRole(organization);

            Membership membership = membershipRepository.save(
                    new Membership(organization, owner, Membership.Status.ACTIVE));

            membershipRoleRepository.save(new MembershipRole(tenantId, membership, ownerRole));

            Subscription subscription = subscriptionActivation.activateTrial(tenantId, organization);

            outboxWriter.append(
                    tenantId, "organization.onboarded", "organization",
                    organization.getId(),
                    Map.of("name", organization.getName(), "plan", "trial"));

            return new OnboardOrganizationResult(
                    organization.getId(),
                    legalEntity.getId(),
                    branch.getId(),
                    owner.getId(),
                    ownerRole.getId(),
                    membership.getId(),
                    subscription.getId());
        });
    }
}
